import { shallowMount, flushPromises } from '@vue/test-utils'
import EditInstanceProxy from '@/views/compute/EditInstanceProxy.vue'
import { getAPI, postAPI } from '@/api'

jest.mock('@/api', () => ({ getAPI: jest.fn(), postAPI: jest.fn() }))

let wrapper
let jobs
const proxy = { id: 'proxy-1', name: 'myapp', fqdn: 'myapp.apps.example.com', protocol: 'http', port: 8080 }
const resource = { id: 'vm-1' }

async function mountForm (customNames = true) {
  jobs = []
  getAPI.mockResolvedValue({ listreverseproxydomainsresponse: { reverseproxydomain: [{ domain: 'apps.example.com', allowcustomname: customNames }] } })
  wrapper = shallowMount(EditInstanceProxy, {
    props: { resource, proxy },
    global: {
      mocks: {
        $t: key => key,
        $notifyError: jest.fn(),
        $notification: { success: jest.fn() },
        $pollJob: options => jobs.push(options)
      },
      stubs: {
        'a-tooltip': { template: '<span><slot /></span>' },
        'a-button': { template: '<button><slot /></button>' }
      }
    }
  })
  await flushPromises()
}

beforeEach(() => { jest.clearAllMocks() })
afterEach(() => { if (wrapper) wrapper.unmount() })

test('prefills the current prefix and keeps the suffix fixed', async () => {
  await mountForm()
  expect(wrapper.vm.name).toBe('myapp')
  expect(wrapper.vm.suffix).toBe('apps.example.com')
  expect(wrapper.vm.canSave).toBe(false)
  expect(getAPI).toHaveBeenCalledWith('listReverseProxyDomains', { virtualmachineid: 'vm-1' })
})

test('updates the existing exposure and waits for completion before closing', async () => {
  await mountForm()
  postAPI.mockResolvedValue({ updateinstanceproxyresponse: { jobid: 'job-1' } })
  await wrapper.setData({ name: ' newname ' })
  wrapper.vm.save()
  await flushPromises()
  expect(postAPI).toHaveBeenCalledWith('updateInstanceProxy', { id: 'proxy-1', name: 'newname', protocol: 'http', port: 8080 })
  expect(wrapper.vm.loading).toBe(true)
  expect(wrapper.emitted('saved')).toBeUndefined()
  wrapper.vm.save()
  expect(postAPI).toHaveBeenCalledTimes(1)
  jobs[0].successMethod({ instanceproxy: { ...proxy, name: 'newname' } })
  await flushPromises()
  expect(wrapper.emitted('saved')).toHaveLength(1)
  expect(wrapper.vm.loading).toBe(false)
})

test('a failed update keeps the form open with the entered name and an error', async () => {
  await mountForm()
  postAPI.mockResolvedValue({ updateinstanceproxyresponse: { jobid: 'job-1' } })
  await wrapper.setData({ name: 'taken' })
  wrapper.vm.save()
  await flushPromises()
  jobs[0].errorMethod({ jobresult: { errortext: 'Name is already in use' } })
  await flushPromises()
  expect(wrapper.vm.error).toBe('Name is already in use')
  expect(wrapper.vm.name).toBe('taken')
  expect(wrapper.emitted('saved')).toBeUndefined()
  expect(wrapper.vm.canSave).toBe(true)
})

test('admin policy disables custom edits and prevents submitting them', async () => {
  await mountForm(false)
  await wrapper.setData({ name: 'newname' })
  await wrapper.vm.save()
  expect(wrapper.vm.canSave).toBe(false)
  expect(postAPI).not.toHaveBeenCalled()
})

test('a policy lookup failure leaves saving disabled', async () => {
  await mountForm()
  getAPI.mockRejectedValueOnce(new Error('Unavailable'))
  wrapper.unmount()
  wrapper = shallowMount(EditInstanceProxy, { props: { resource, proxy }, global: { mocks: { $t: key => key, $notifyError: jest.fn() } } })
  await flushPromises()
  await wrapper.setData({ name: 'newname' })
  expect(wrapper.vm.canSave).toBe(false)
})

test('random-only policy still permits backend edits without submitting the existing name', async () => {
  await mountForm(false)
  await wrapper.setData({ protocol: 'https', port: 8443 })
  postAPI.mockResolvedValue({ updateinstanceproxyresponse: { instanceproxy: {} } })
  await wrapper.vm.save()
  expect(postAPI).toHaveBeenCalledWith('updateInstanceProxy', { id: 'proxy-1', protocol: 'https', port: 8443 })
})

test('random names are generated by the server when requested', async () => {
  await mountForm(false)
  await wrapper.setData({ generateName: true })
  postAPI.mockResolvedValue({ updateinstanceproxyresponse: { instanceproxy: {} } })
  await wrapper.vm.save()
  expect(postAPI).toHaveBeenCalledWith('updateInstanceProxy', { id: 'proxy-1', generatename: true, protocol: 'http', port: 8080 })
})

test('invalid backend ports cannot be submitted', async () => {
  await mountForm()
  for (const port of [0, 65536, null, 80.5]) {
    await wrapper.setData({ port })
    await wrapper.vm.save()
  }
  expect(postAPI).not.toHaveBeenCalled()
})
